/**
 * Delete event from Google Calendar
 */
export async function deleteCalendarEvent(eventId: string, token: string): Promise<boolean> {
  try {
    await callCalendarApi(`/calendars/primary/events/${eventId}`, 'DELETE', token);
    return true;
  } catch (error) {
    console.warn('Could not delete calendar event:', error);
    return false;
  }
}

/**
 * Utility: Gets YYYY-MM-DD of the day after specified YYYY-MM-DD
 */
function getNextDayString(dateStr: string): string {
  const parts = dateStr.split('-');
  if (parts.length !== 3) return dateStr;
  const year = parseInt(parts[0], 10);
  const month = parseInt(parts[1], 10) - 1;
  const day = parseInt(parts[2], 10);

  const d = new Date(year, month, day);
  d.setDate(d.getDate() + 1);

  const y4 = d.getFullYear();
  const m2 = String(d.getMonth() + 1).padStart(2, '0');
  const d2 = String(d.getDate()).padStart(2, '0');

  return `${y4}-${m2}-${d2}`;
}
